    /// Replaces the asset source and clears source-dependent GPU caches.
    pub fn set_assets(&mut self, assets: Assets) {
        self.assets = assets;
        self.environment.cache.clear();
        self.interpolator.reset();
        self.pipelines.clear();
        self.meshes.clear();
        self.textures.clear();
        self.views.clear();
        self.materials.clear();
        self.dynamic.clear();
        self.dynamic_errors.clear();
        self.clear_thumbnails();
    }

    /// Drops cached assets whose files changed on disk. Call a few times per second.
    /// Invalidates changed file-backed resources so they reload on the next use.
    /// Packed/built-in assets have no modification timestamps.
    pub fn refresh_changed(&mut self) {
        let views_changed = self.views.invalidate_changed(&self.assets);
        self.environment.cache.invalidate_changed(&self.assets);
        if views_changed {
            self.materials.clear();
        }
        let changed = views_changed
            | self.pipelines.invalidate_changed(&self.assets)
            | self.meshes.invalidate_changed(&self.assets)
            | self.textures.invalidate_changed(&self.assets);
        if changed {
            self.clear_thumbnails();
        }
    }

    /// Releases cached preview textures and their egui registrations.
    pub fn clear_thumbnails(&mut self) {
        let mut egui_renderer = self.rs.renderer.write();
        for id in self.thumbs.drain().filter_map(|(_, id)| id) {
            egui_renderer.free_texture(&id);
        }
    }

    /// A small lit preview of a mesh (optionally with a custom shader), rendered once on the GPU
    /// and cached. `mesh` is any mesh key; use `primitive:sphere` to preview a shader.
    /// Whether a preview for this exact geometry/shader/size key is already cached.
    pub fn has_thumbnail(&self, mesh: &str, shader: &str, size: u32) -> bool {
        self.thumbs.contains_key(&format!("{mesh}|{shader}|{size}"))
    }

    /// Returns a cached or newly rendered square asset preview.
    /// Loading failures return `None` and can be read through [`Self::take_errors`].
    pub fn thumbnail(&mut self, mesh: &str, shader: &str, size: u32) -> Option<TextureId> {
        let key = format!("{mesh}|{shader}|{size}");
        if let Some(t) = self.thumbs.get(&key) {
            return *t;
        }
        let limit = self.device.limits().max_texture_dimension_2d.min(1024);
        let id = if size == 0 || size > limit {
            self.errors.push(format!("thumbnail dimensions must be 1..={limit} pixels"));
            None
        } else {
            self.render_thumbnail(mesh, shader, size)
        };
        self.thumbs.insert(key, id);
        id
    }

    fn render_thumbnail(&mut self, mesh: &str, shader: &str, size: u32) -> Option<TextureId> {
        use kvas_engine::hierarchy;
        let (min, max) = self.mesh_bounds(mesh)?;
        let mut scene = Scene::default();
        scene.settings.sky = [0.16, 0.17, 0.19];
        scene.settings.ambient = [0.32, 0.33, 0.36];
        let w = &mut scene.world;
        let e = hierarchy::spawn_named(w, "preview");
        w.insert(
            e,
            MeshRenderer {
                mesh: mesh.to_string(),
                shader: shader.to_string(),
                color: [0.82, 0.84, 0.9, 1.0],
                roughness: 0.45,
                ..Default::default()
            },
        );
        w.insert(e, GlobalTransform(Mat4::IDENTITY));
        let sun = w.spawn();
        w.insert(sun, Light { intensity: 1.3, ..Default::default() });
        w.insert(
            sun,
            GlobalTransform(Mat4::from_rotation_translation(glam::Quat::from_euler(glam::EulerRot::YXZ, -0.6, -0.8, 0.0), Vec3::ZERO)),
        );
        let fill = w.spawn();
        w.insert(fill, Light { kind: LightKind::Point, intensity: 0.8, range: 40.0, color: [0.6, 0.7, 1.0, 1.0], ..Default::default() });
        let center = (min + max) * 0.5;
        let radius = ((max - min).length() * 0.5).max(0.01);
        w.insert(fill, GlobalTransform(Mat4::from_translation(center + Vec3::new(-2.0, 1.0, 2.0) * radius)));
        let eye = center + Vec3::new(1.0, 0.65, 1.25).normalize() * radius * 2.7;
        let view = View::new(glam::camera::rh::view::look_at_mat4(eye, center, Vec3::Y).inverse(), 40.0, 1.0, radius * 0.1, radius * 12.0);
        let targets = make_targets(&self.device, [size, size], None);
        let debug = DebugDraw::default();
        self.draw(&scene, &Frame { view, size: [size, size], time: 0.0, dt: 0.0, debug: &debug, shadows: false, debug_view: 0, cinematic: false }, &targets);
        let id = self.rs.renderer.write().register_native_texture(&self.device, &targets.resolve, wgpu::FilterMode::Linear);
        Some(id)
    }

